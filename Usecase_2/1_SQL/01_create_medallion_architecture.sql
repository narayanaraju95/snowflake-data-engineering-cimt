-- ============================================================
-- 2. GENERATE 20 CUSTOMERS
-- ============================================================

INSERT INTO BRONZE.RAW_CUSTOMERS
SELECT
    CASE WHEN N = 20 THEN 19 ELSE N END,
    CASE WHEN N = 5 THEN NULL
         ELSE 'Customer ' || N END,
    CASE WHEN N = 8 THEN 'invalid-email'
         ELSE 'customer' || N || '@example.com' END,
    CASE WHEN MOD(N,3) = 0 THEN 'Netherlands'
         WHEN MOD(N,3) = 1 THEN 'Germany'
         ELSE 'Belgium' END,
    CASE WHEN MOD(N,3) = 0 THEN 'Amsterdam'
         WHEN MOD(N,3) = 1 THEN 'Berlin'
         ELSE 'Brussels' END,
    DATEADD(DAY, -N, CURRENT_DATE()),
    CURRENT_TIMESTAMP()::TIMESTAMP_NTZ
FROM (
    SELECT ROW_NUMBER() OVER (ORDER BY SEQ4()) AS N
    FROM TABLE(GENERATOR(ROWCOUNT => 20))
);

-- ============================================================
-- 3. GENERATE 10 PRODUCTS
-- ============================================================

INSERT INTO BRONZE.RAW_PRODUCTS
SELECT
    100 + N,
    'Product ' || N,
    CASE MOD(N,4)
        WHEN 0 THEN 'Electronics'
        WHEN 1 THEN 'Clothing'
        WHEN 2 THEN 'Furniture'
        ELSE 'Accessories'
    END,
    CASE WHEN N = 10 THEN NULL
         ELSE (N * 25.50)::NUMBER(10,2) END,
    CURRENT_TIMESTAMP()::TIMESTAMP_NTZ
FROM (
    SELECT ROW_NUMBER() OVER (ORDER BY SEQ4()) AS N
    FROM TABLE(GENERATOR(ROWCOUNT => 10))
);

-- ============================================================
-- 4. GENERATE 30 ORDERS
-- ============================================================

INSERT INTO BRONZE.RAW_ORDERS
SELECT
    1000 + N,
    MOD(N - 1, 19) + 1,
    DATEADD(DAY, -MOD(N, 90), CURRENT_DATE()),
    CASE
        WHEN N = 10 THEN NULL
        WHEN MOD(N,3) = 0 THEN 'COMPLETED'
        WHEN MOD(N,3) = 1 THEN 'PENDING'
        ELSE 'CANCELLED'
    END,
    CURRENT_TIMESTAMP()::TIMESTAMP_NTZ
FROM (
    SELECT ROW_NUMBER() OVER (ORDER BY SEQ4()) AS N
    FROM TABLE(GENERATOR(ROWCOUNT => 30))
);

-- ============================================================
-- 5. GENERATE 40 ORDER ITEMS
-- ============================================================

INSERT INTO BRONZE.RAW_ORDER_ITEMS
SELECT
    2000 + N,
    1000 + MOD(N - 1, 30) + 1,
    CASE WHEN N = 40 THEN 999
         ELSE 100 + MOD(N - 1, 10) + 1 END,
    CASE WHEN N = 5 THEN 0
         ELSE MOD(N,5) + 1 END,
    CASE WHEN N = 8 THEN -50
         ELSE (100 + MOD(N,10) * 25)::NUMBER(10,2) END,
    CURRENT_TIMESTAMP()::TIMESTAMP_NTZ
FROM (
    SELECT ROW_NUMBER() OVER (ORDER BY SEQ4()) AS N
    FROM TABLE(GENERATOR(ROWCOUNT => 40))
);

